-- Assessment & Peer Review: the final demonstration of a completed path (US28). The student chooses a modality and
-- a moment and a verifier enabled in a skill of the path is assigned. A path has at most one demonstration that
-- still counts (scheduled, with video or approved); a rejected or cancelled one lets the student schedule another.
CREATE TABLE final_demonstrations (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    student_id integer NOT NULL,
    learning_path_id integer NOT NULL,
    skill_tag character varying(100) NOT NULL,
    verifier_user_id integer NOT NULL,
    modality character varying(30) NOT NULL,
    scheduled_at timestamp with time zone NOT NULL,
    status character varying(30) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_final_demonstrations PRIMARY KEY (id),
    CONSTRAINT ck_final_demonstrations_modality CHECK (modality IN ('AdvancedProject', 'SupervisedExam')),
    CONSTRAINT ck_final_demonstrations_status CHECK (status IN ('Scheduled', 'VideoSubmitted', 'Approved', 'Rejected', 'Cancelled')),
    CONSTRAINT ck_final_demonstrations_parties CHECK (student_id <> verifier_user_id)
);

CREATE UNIQUE INDEX uq_final_demonstrations_active_path ON final_demonstrations (learning_path_id)
    WHERE status IN ('Scheduled', 'VideoSubmitted', 'Approved');
CREATE INDEX ix_final_demonstrations_student ON final_demonstrations (student_id, created_at DESC);
CREATE INDEX ix_final_demonstrations_verifier ON final_demonstrations (verifier_user_id, scheduled_at);
