-- Recognition & Incentives: the Idempotency-Key of a redemption (POST /api/v1/credit-transactions/redeem). The
-- app sends one key per attempt; a retry with the same key answers the stored movement instead of charging again.
-- The key is saved in the same transaction as the debit, so a failed redemption stores nothing.
CREATE TABLE redemption_idempotency_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    idempotency_key character varying(64) NOT NULL,
    credit_transaction_id integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_redemption_idempotency_keys PRIMARY KEY (id),
    -- A key belongs to the user that sent it: the same key from another user is another redemption. Two
    -- simultaneous requests with the same key cannot both store it, so only one of them charges.
    CONSTRAINT uq_redemption_idempotency_keys_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT fk_redemption_idempotency_keys_credit_transactions FOREIGN KEY (credit_transaction_id)
        REFERENCES credit_transactions (id) ON DELETE CASCADE
);

CREATE INDEX ix_redemption_idempotency_keys_credit_transaction
    ON redemption_idempotency_keys (credit_transaction_id);
