-- Assessment & Peer Review: the delivery of a mini-project (the link to the repository of the student). A mini-project is
-- delivered once, so a second delivery of the same one is rejected by the database as well.
CREATE TABLE mini_project_submissions (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    mini_project_id integer NOT NULL,
    student_id integer NOT NULL,
    path_node_id integer NOT NULL,
    skill_tag character varying(100) NOT NULL,
    repository_url character varying(500) NOT NULL,
    submitted_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_mini_project_submissions PRIMARY KEY (id),
    CONSTRAINT uq_mini_project_submissions_mini_project UNIQUE (mini_project_id)
);

CREATE INDEX ix_mini_project_submissions_student_node ON mini_project_submissions (student_id, path_node_id);
