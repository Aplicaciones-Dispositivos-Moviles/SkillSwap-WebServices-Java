-- Assessment & Peer Review: a Verificador senior can order the reevaluation of an approved result, so the student
-- demonstrates the skill again. Every order is kept with its justification, as an audit trail.
CREATE TABLE reevaluations (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    source_type character varying(20) NOT NULL,
    source_id integer NOT NULL,
    student_id integer NOT NULL,
    ordered_by_user_id integer NOT NULL,
    justification character varying(2000) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_reevaluations PRIMARY KEY (id),
    CONSTRAINT ck_reevaluations_source_type CHECK (source_type IN ('Attempt', 'Case'))
);

CREATE INDEX ix_reevaluations_source ON reevaluations (source_type, source_id);

-- How many times a reevaluation reopened an approved case. The cases that were never reevaluated have 0.
ALTER TABLE verification_cases
    ADD COLUMN reevaluation_count integer NOT NULL DEFAULT 0;
