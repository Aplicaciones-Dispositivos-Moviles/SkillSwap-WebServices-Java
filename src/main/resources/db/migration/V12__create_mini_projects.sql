-- Learning Path Engine: the mini-project generated for a path node (US19). It carries the statement the student
-- develops, the rubric it will be evaluated with and the fixed deadline to deliver it. Older mini-projects of a node
-- are kept as history; the latest one is the one that can be delivered.
CREATE TABLE mini_projects (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    path_node_id integer NOT NULL,
    skill_tag character varying(100) NOT NULL,
    title character varying(150) NOT NULL,
    statement character varying(4000) NOT NULL,
    rubric jsonb NOT NULL,
    passing_score integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    due_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_mini_projects PRIMARY KEY (id)
);

CREATE INDEX ix_mini_projects_path_node_id ON mini_projects (path_node_id);
