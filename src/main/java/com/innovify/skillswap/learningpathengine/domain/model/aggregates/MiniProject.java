package com.innovify.skillswap.learningpathengine.domain.model.aggregates;

import com.innovify.skillswap.learningpathengine.domain.model.entities.RubricCriterion;
import com.innovify.skillswap.learningpathengine.domain.model.valueobjects.MiniProjectDraft;
import com.innovify.skillswap.learningpathengine.infrastructure.persistence.jpa.converters.RubricCriterionListConverter;
import com.innovify.skillswap.shared.domain.exceptions.DomainException;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Duration;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.Collection;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;

/**
 * The practical assessment generated by AI for one path node (US19): a statement the student develops, the rubric
 * it will be evaluated with and the fixed deadline to deliver it. It is consumed by Assessment &amp; Peer Review, which
 * receives the delivery. Older mini-projects of a node are kept as history; the latest is the one that can be delivered.
 *
 * <p>The rubric is stored in the JSON column of the mini-project, never as an entity of its own. The converter that
 * writes it is the one JPA annotation of this class that points outside the domain, because a list cannot be matched
 * by an auto-applied converter.
 */
@Entity
@Table(name = "mini_projects")
public class MiniProject {

    public static final int MIN_CRITERIA = 4;
    public static final int MAX_CRITERIA = 6;
    public static final int TOTAL_WEIGHT = 100;
    /** The score (out of {@value #TOTAL_WEIGHT}) the delivery needs to be approved by the preliminary evaluation. */
    public static final int PASSING_SCORE = 70;
    public static final Duration DELIVERY_PERIOD = Duration.ofDays(5);
    public static final int MAX_TITLE_LENGTH = 150;
    public static final int MAX_STATEMENT_LENGTH = 4000;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private Integer id;

    @Column(name = "path_node_id", nullable = false)
    private int pathNodeId;

    @Column(name = "skill_tag", nullable = false, length = 100)
    private String skillTag;

    @Column(name = "title", nullable = false, length = 150)
    private String title;

    @Column(name = "statement", nullable = false, length = 4000)
    private String statement;

    @Convert(converter = RubricCriterionListConverter.class)
    @Column(name = "rubric", nullable = false, columnDefinition = "jsonb")
    private List<RubricCriterion> rubric;

    @Column(name = "passing_score", nullable = false)
    private int passingScore;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    @Column(name = "due_at", nullable = false)
    private Instant dueAt;

    /** Required by JPA. */
    protected MiniProject() {
    }

    /**
     * A mini-project that can be delivered for {@code DELIVERY_PERIOD} from now.
     *
     * @throws DomainException when the node or the skill are not valid, the title or the statement are empty or too
     *                         long, or the rubric does not have %d to %d different criteria whose weights add up to
     *                         %d
     */
    public MiniProject(int pathNodeId, String skillTag, String title, String statement,
                       Collection<RubricCriterion> rubric) {
        if (pathNodeId <= 0) {
            throw new DomainException("The mini-project must belong to a valid path node.");
        }
        if (skillTag == null || skillTag.isBlank()) {
            throw new DomainException("The skill tag cannot be empty.");
        }
        if (title == null || title.isBlank()) {
            throw new DomainException("The title of the mini-project cannot be empty.");
        }
        if (title.strip().length() > MAX_TITLE_LENGTH) {
            throw new DomainException("The title of the mini-project cannot exceed %d characters."
                    .formatted(MAX_TITLE_LENGTH));
        }
        if (statement == null || statement.isBlank()) {
            throw new DomainException("The statement of the mini-project cannot be empty.");
        }
        if (statement.strip().length() > MAX_STATEMENT_LENGTH) {
            throw new DomainException("The statement of the mini-project cannot exceed %d characters."
                    .formatted(MAX_STATEMENT_LENGTH));
        }

        List<RubricCriterion> criteria = rubric == null ? List.of() : List.copyOf(rubric);
        if (criteria.size() < MIN_CRITERIA || criteria.size() > MAX_CRITERIA) {
            throw new DomainException("The rubric needs between %d and %d criteria.".formatted(MIN_CRITERIA, MAX_CRITERIA));
        }
        Set<String> names = new TreeSet<>(String.CASE_INSENSITIVE_ORDER);
        criteria.forEach(criterion -> names.add(criterion.getName()));
        if (names.size() != criteria.size()) {
            throw new DomainException("The criteria of the rubric must be different from each other.");
        }
        if (criteria.stream().mapToInt(RubricCriterion::getWeight).sum() != TOTAL_WEIGHT) {
            throw new DomainException("The weights of the rubric must add up to %d.".formatted(TOTAL_WEIGHT));
        }

        this.pathNodeId = pathNodeId;
        this.skillTag = skillTag.strip();
        this.title = title.strip();
        this.statement = statement.strip();
        this.rubric = criteria;
        this.passingScore = PASSING_SCORE;
        // PostgreSQL keeps microseconds and rounds the rest: truncated here, the deadline read back is the same one on
        // every OS (the clock of Windows has 100 ns steps).
        this.createdAt = Instant.now().truncatedTo(ChronoUnit.MICROS);
        this.dueAt = createdAt.plus(DELIVERY_PERIOD);
    }

    /** A mini-project built from what the generator proposed. */
    public MiniProject(int pathNodeId, String skillTag, MiniProjectDraft draft) {
        this(pathNodeId, skillTag, draft == null ? null : draft.title(), draft == null ? null : draft.statement(),
                draft == null ? null : draft.rubric());
    }

    /** Whether the deadline to deliver it passed at that moment. */
    public boolean isExpired(Instant now) {
        return now.isAfter(dueAt);
    }

    public Integer getId() {
        return id;
    }

    public int getPathNodeId() {
        return pathNodeId;
    }

    public String getSkillTag() {
        return skillTag;
    }

    public String getTitle() {
        return title;
    }

    public String getStatement() {
        return statement;
    }

    public List<RubricCriterion> getRubric() {
        return rubric;
    }

    public int getPassingScore() {
        return passingScore;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getDueAt() {
        return dueAt;
    }
}
