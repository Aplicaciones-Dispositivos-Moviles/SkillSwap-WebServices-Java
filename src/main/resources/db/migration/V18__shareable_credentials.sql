-- Recognition & Incentives: a student shares a verified skill with a public link (T57). The link carries an
-- unguessable token, has no expiry, and there is one per student and skill, so asking again returns the same one.
CREATE TABLE shareable_credentials (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    owner_id integer NOT NULL,
    skill_tag character varying(100) NOT NULL,
    token character varying(64) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT "PK_shareable_credentials" PRIMARY KEY (id)
);

CREATE UNIQUE INDEX ux_shareable_credentials_token ON shareable_credentials (token);
CREATE UNIQUE INDEX ux_shareable_credentials_owner_skill ON shareable_credentials (owner_id, skill_tag);
